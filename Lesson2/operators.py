# Các phép toán:
    # Cơ bản: + - * /
    # Chia lấy nguyên: //
    # Chia lấy dư: %
    # Lũy thừa: **
# Lưu ý: Lũy thừa sẽ được thực hiện từ phải qua trái
# Thứ tự thực hiện: Lũy thừa -> Nhân chia -> Cộng trừ
print('7 / 2 =', 7 / 2)
print('7 // 2 =', 7 // 2)
print('7 % 2 =', 7 % 2)
print('7 ** 2 =', 7 ** 2)

# Toán tử quan hệ (phép so sánh):
    # So sánh bằng: ==
print('7 == 2:', 7 == 2)    # False
print('7 == 7:', 7 == 7)    # True

    # So sánh khác: !=
print('7 != 2:', 7 != 2)    # True
print('7 != 7:', 7 != 7)    # False

    # So sánh lớn hơn / nhỏ hơn: > <
print('7 > 2:', 7 > 2)    # True
print('7 < 2:', 7 < 2)    # False

    # So sánh lớn / nhỏ hơn hoặc bằng: >= <=
print('7 >= 2:', 7 >= 2)    # True
print('7 <= 2:', 7 <= 2)    # False

# Toán tử logic: and - or - not
# Ví dụ: trà sữa - gàn rán