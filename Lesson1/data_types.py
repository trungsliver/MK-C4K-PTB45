# Data type - Kiểu dữ liệu 
    # string: chuỗi / xâu ký tự
name = 'Duc Trung'
address = "Ha Noi"
phone = '0987654321'

    # int (integer): số nguyên
age = 2
siblings = 1

    # float: số thực (số thập phân)
score = 8.5
height = 1.7

    # Bool / boolean: logic, chỉ có True / False (Đúng / Sai)
is_male = True
alien = False

# Cách kiểm tra kiểu dữ liệu - type()
print(type(name))
print(type(age))
print(type(score))
print(type(is_male))